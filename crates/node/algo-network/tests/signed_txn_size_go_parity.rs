//! Issue #2621: `algo_types::signed_txn_size::signed_txn_size` against go
//! v5.1.1-stable's `signedTxnSize` (`data/txHandler.go`), which
//! `TestCheckCanonicalEncoding`'s `size` case asserts. Every row of
//! `fixtures/signed_txn_size_go.jsonl` is a transaction go encoded
//! (`protocol.Encode`) together with go's size of it; the fixture is generated by
//! `tools/signed-txn-size-oracle` (see its header for the command).

use algo_network::tx_tag_handler::decode_tx_message;
use algo_types::signed_txn_size::signed_txn_size;
use base64::Engine;

#[test]
fn signed_txn_size_matches_go_for_every_oracle_row() {
    let fixture = include_str!("fixtures/signed_txn_size_go.jsonl");
    let mut rows = 0;
    for line in fixture.lines().filter(|l| !l.trim().is_empty()) {
        let row: serde_json::Value = serde_json::from_str(line).unwrap();
        let name = row["name"].as_str().unwrap();
        let data = base64::engine::general_purpose::STANDARD
            .decode(row["stxn"].as_str().unwrap())
            .unwrap();
        let want = row["size"].as_i64().unwrap();
        let group = decode_tx_message(&data).unwrap_or_else(|e| panic!("{name}: decode: {e}"));
        assert_eq!(group.len(), 1, "{name}");
        assert_eq!(signed_txn_size(&group[0]), want, "{name}");
        rows += 1;
    }
    assert!(rows >= 30, "fixture has {rows} rows");
}
