//! Static-check corpus replay (issue #2286): `algo_avm::check` against go's
//! `logic.CheckSignature` / `logic.CheckContract` verdicts for the programs
//! of `tests/fixtures/avm/check_corpus.jsonl` (generated by
//! `tools/avm-opcode-capture/checkfuzz.go`).
//!
//! The port is CONSERVATIVE, and that is what is asserted:
//!   * a program go's check accepts is NEVER rejected here (a false rejection
//!     would fork consensus: an application create/update go applies would be
//!     refused), and
//!   * a rejection carries go's exact `pc=%3d <err>` text.
//!
//! A program go rejects may still pass here when it hits a construct that is
//! not ported (pre-v4 static cost bound, prefix-family immediates, ...); the
//! floor on the number of rejections keeps the corpus from passing vacuously.

use algo_avm::check::{contract_static_check, logicsig_static_check};
use serde::Deserialize;
use std::path::PathBuf;

#[derive(Deserialize)]
struct Record {
    name: String,
    program: String,
    check_error: String,
    check_app_error: String,
}

fn load() -> Vec<Record> {
    let mut p = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    p.push("tests/fixtures/avm/check_corpus.jsonl");
    let raw = std::fs::read_to_string(&p).expect("read check corpus");
    raw.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| serde_json::from_str(l).expect("parse corpus line"))
        .collect()
}

/// Compare one verdict; `Err` describes a violation of the conservative rule.
fn verdict(rust: Option<String>, go: &str) -> Result<bool, String> {
    match rust {
        None => Ok(false),
        Some(text) if text == go => Ok(true),
        Some(text) => Err(format!("rust {text:?} vs go {go:?}")),
    }
}

#[test]
fn static_check_never_rejects_what_go_accepts_and_matches_go_text() {
    let records = load();
    assert!(records.len() >= 3000, "the corpus is present");
    let mut bad = Vec::new();
    let (mut sig_rejected, mut app_rejected) = (0usize, 0usize);
    for r in &records {
        let program = hex::decode(&r.program).expect("program hex");
        match verdict(logicsig_static_check(&program), &r.check_error) {
            Ok(true) => sig_rejected += 1,
            Ok(false) => {}
            Err(e) => bad.push(format!("{} (LogicSig {}): {e}", r.name, r.program)),
        }
        match verdict(contract_static_check(&program), &r.check_app_error) {
            Ok(true) => app_rejected += 1,
            Ok(false) => {}
            Err(e) => bad.push(format!("{} (app {}): {e}", r.name, r.program)),
        }
    }
    assert!(
        bad.is_empty(),
        "{} static-check verdicts differ from go:\n{}",
        bad.len(),
        bad.iter().take(40).cloned().collect::<Vec<_>>().join("\n")
    );
    // The rejections the port covers, so the check cannot silently regress to
    // "never rejects".
    assert!(
        sig_rejected >= 1500 && app_rejected >= 1500,
        "too few rejections replayed: sig={sig_rejected} app={app_rejected}"
    );
}
