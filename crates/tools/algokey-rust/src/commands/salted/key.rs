//! Salted-key private-key file format, mirroring
//! `../go-algorand/cmd/algokey/salted_key.go` (v5.1.1-stable).
//!
//! `saltedPublicMaterial`/`saltedSigningMaterial` are Go's `codec`-tagged structs;
//! their msgpack encoding is generated by `msgp` (see `msgp_gen.go`) with
//! **unconditional** (no `omitempty`) fields in lexicographic key order:
//! `saltedPublicMaterial{"public-key", "salt", "scheme"}` and
//! `saltedSigningMaterial{"private-key", "public"}`. We reproduce those exact
//! bytes by hand (via `rmp::encode`/`rmp::decode`) so a keyfile generated by
//! this binary and by real `algokey salted generate` are interchangeable.

use std::path::Path;

use algo_types::raw_text::go_lossy;
use algo_types::{salted_address, Address, AddressSalt};

use super::msgp_text::{wrap, MErr, Rd, R};
use super::scheme::{ops_for, scheme_not_supported};
use super::{read_file, write_file, ERR_SALTED_KEY_MALFORMED, ERR_SALT_ON_CURVE};

/// A signature-scheme public key with its address salt (Go: `saltedPublicMaterial`,
/// `salted_key.go:35-41`).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct SaltedPublicMaterial {
    pub scheme: [u8; 2],
    pub salt: AddressSalt,
    pub public_key: Vec<u8>,
}

impl SaltedPublicMaterial {
    /// Mirrors `saltedPublicMaterial.address()` (`salted_key.go:43-45`).
    pub fn address(&self) -> Address {
        salted_address(self.scheme, self.salt, &self.public_key)
    }

    /// Mirrors `saltedPublicMaterial.validate()` (`salted_key.go:47-59`).
    pub fn validate(&self) -> Result<(), String> {
        let ops = ops_for(self.scheme).ok_or_else(|| scheme_not_supported(&self.scheme))?;
        if self.public_key.len() != ops.public_key_size() {
            return Err(format!(
                "{ERR_SALTED_KEY_MALFORMED}: got public key size {}, want {}",
                self.public_key.len(),
                ops.public_key_size()
            ));
        }
        if !self.address().is_off_ed25519_curve() {
            return Err(format!("{ERR_SALT_ON_CURVE}: address {}", self.address()));
        }
        Ok(())
    }
}

/// A signature-scheme private key with its public envelope (Go: `saltedSigningMaterial`,
/// `salted_key.go:64-69`). Key files hold the scheme's working keys, never the
/// mnemonic entropy they were derived from.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct SaltedSigningMaterial {
    pub public: SaltedPublicMaterial,
    pub private_key: Vec<u8>,
}

impl SaltedSigningMaterial {
    /// Mirrors `saltedSigningMaterial.validate()` (`salted_key.go:71-80`).
    pub fn validate(&self) -> Result<(), String> {
        self.public.validate()?;
        let ops = ops_for(self.public.scheme).expect("validated by the public material");
        if self.private_key.len() != ops.private_key_size() {
            return Err(format!(
                "{ERR_SALTED_KEY_MALFORMED}: got private key size {}, want {}",
                self.private_key.len(),
                ops.private_key_size()
            ));
        }
        Ok(())
    }
}

/// Encode a `SaltedSigningMaterial` exactly as Go's `protocol.Encode(&signing)`
/// would (`salted_key.go:82-87`): an unconditional, alphabetically key-ordered
/// msgpack map, nested one level for `public`.
pub fn encode_salted_signing_material(m: &SaltedSigningMaterial) -> Vec<u8> {
    let mut out = Vec::new();
    // saltedSigningMaterial: {"private-key", "public"} (alphabetical).
    rmp::encode::write_map_len(&mut out, 2).unwrap();
    rmp::encode::write_str(&mut out, "private-key").unwrap();
    rmp::encode::write_bin(&mut out, &m.private_key).unwrap();
    rmp::encode::write_str(&mut out, "public").unwrap();
    encode_salted_public_material(&mut out, &m.public);
    out
}

pub(super) fn encode_salted_public_material(out: &mut Vec<u8>, p: &SaltedPublicMaterial) {
    // saltedPublicMaterial: {"public-key", "salt", "scheme"} (alphabetical).
    rmp::encode::write_map_len(out, 3).unwrap();
    rmp::encode::write_str(out, "public-key").unwrap();
    rmp::encode::write_bin(out, &p.public_key).unwrap();
    rmp::encode::write_str(out, "salt").unwrap();
    rmp::encode::write_uint(out, p.salt.0 as u64).unwrap();
    rmp::encode::write_str(out, "scheme").unwrap();
    rmp::encode::write_bin(out, &p.scheme).unwrap();
}

/// Decode a `SaltedSigningMaterial` previously produced by
/// [`encode_salted_signing_material`] (or by real go-algorand `algokey salted
/// generate`/`import`), exactly as go's `protocol.Decode` of a
/// `saltedSigningMaterial` does (`decodeSaltedPrivateKeyFileBytes` before its
/// `validate()`), with go's error texts: the msgp-generated `UnmarshalMsg`
/// (`cmd/algokey/msgp_gen.go`, msgp 1.1.66) reads a map or a `nil` (a zero
/// struct), no positional array form; a key the struct lacks is
/// `Unknown field`, a repeated key decodes into the populated field, a missing
/// field stays zero (`validate` rejects it later) and the bytes after the
/// value are ignored.
pub fn decode_salted_signing_material(data: &[u8]) -> Result<SaltedSigningMaterial, String> {
    let mut rd = Rd(data);
    let mut m = SaltedSigningMaterial::default();
    unmarshal_signing(&mut rd, &mut m).map_err(|e| format!("{ERR_SALTED_KEY_MALFORMED}: {e}"))?;
    Ok(m)
}

/// `saltedPublicMaterial.UnmarshalMsg` on its own (go's
/// `TestMarshalUnmarshalsaltedPublicMaterial`).
#[cfg(test)]
pub(super) fn decode_salted_public_material(data: &[u8]) -> Result<SaltedPublicMaterial, String> {
    let mut rd = Rd(data);
    let mut m = SaltedPublicMaterial::default();
    unmarshal_public(&mut rd, &mut m).map_err(|e| e.to_string())?;
    Ok(m)
}

/// The msgpack of a public material alone, as `saltedPublicMaterial.MarshalMsg`.
#[cfg(test)]
pub(super) fn encode_salted_public_material_bytes(p: &SaltedPublicMaterial) -> Vec<u8> {
    let mut out = Vec::new();
    encode_salted_public_material(&mut out, p);
    out
}

fn ctx(name: &str) -> [String; 1] {
    [name.to_string()]
}

/// `saltedSigningMaterial.UnmarshalMsgWithState`.
fn unmarshal_signing(rd: &mut Rd<'_>, z: &mut SaltedSigningMaterial) -> R<()> {
    let (n, nil) = rd.map_header().map_err(|e| wrap(e, &[]))?;
    if nil {
        *z = SaltedSigningMaterial::default();
    }
    for _ in 0..n {
        let key = rd.map_key().map_err(|e| wrap(e, &[]))?;
        match key.as_slice() {
            b"public" => {
                unmarshal_public(rd, &mut z.public).map_err(|e| wrap(e, &ctx("Public")))?
            }
            b"private-key" => {
                z.private_key = rd.bytes().map_err(|e| wrap(e, &ctx("PrivateKey")))?
            }
            other => {
                return Err(wrap(
                    MErr::Plain(format!("Unknown field: {}", go_lossy(other))),
                    &[],
                ))
            }
        }
    }
    Ok(())
}

/// `saltedPublicMaterial.UnmarshalMsgWithState`; its own errors carry no
/// context (the caller adds `Public`).
fn unmarshal_public(rd: &mut Rd<'_>, z: &mut SaltedPublicMaterial) -> R<()> {
    let (n, nil) = rd.map_header().map_err(|e| wrap(e, &[]))?;
    if nil {
        *z = SaltedPublicMaterial::default();
    }
    for _ in 0..n {
        let key = rd.map_key().map_err(|e| wrap(e, &[]))?;
        match key.as_slice() {
            // `SigScheme` and `AddressSalt` unmarshal themselves (an empty
            // wrap), then the caller wraps with the field name.
            b"scheme" => rd
                .exact(&mut z.scheme)
                .map_err(|e| wrap(wrap(e, &[]), &ctx("Scheme")))?,
            b"salt" => {
                z.salt =
                    AddressSalt(rd.uint(8).map_err(|e| wrap(wrap(e, &[]), &ctx("Salt")))? as u8)
            }
            b"public-key" => z.public_key = rd.bytes().map_err(|e| wrap(e, &ctx("PublicKey")))?,
            other => {
                return Err(wrap(
                    MErr::Plain(format!("Unknown field: {}", go_lossy(other))),
                    &[],
                ))
            }
        }
    }
    Ok(())
}

/// Write a private key file at mode 0600 (Go: `writeSaltedPrivateKeyFile`,
/// `salted_key.go:82-87`).
pub fn write_salted_private_key_file(
    path: &Path,
    signing: &SaltedSigningMaterial,
) -> Result<(), String> {
    write_file(path, &encode_salted_signing_material(signing))
        .map_err(|e| format!("cannot write private key to {}: {e}", path.display()))
}

/// go's `decodeSaltedPrivateKeyFileBytes`: decode, then `validate()`.
pub fn decode_salted_private_key_file_bytes(data: &[u8]) -> Result<SaltedSigningMaterial, String> {
    let signing = decode_salted_signing_material(data)?;
    signing.validate()?;
    Ok(signing)
}

/// Read and validate a salted-key private key file (Go:
/// `readSaltedSigningMaterial`, `salted_key.go:89-96`).
pub fn read_salted_signing_material(path: &Path) -> Result<SaltedSigningMaterial, String> {
    let data = read_file(path)
        .map_err(|e| format!("cannot read private key from {}: {e}", path.display()))?;
    decode_salted_private_key_file_bytes(&data)
}

