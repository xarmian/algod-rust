//! `pc_details` parity with go-algorand's `(*EvalContext).pcDetails` (issue
//! #2375, epic #2364): the `opcodes=` text of the failure `Details` of an app
//! call in simulate. Every row of `tests/fixtures/pcdetails_go_parity.jsonl`
//! carries, for one program, go's real `pcDetails` text for every pc in
//! `0..=len+1` (including pcs inside an instruction and past the end). The
//! fixture is generated by `scripts/teal-corpus/pcdetails_fixtures.py` from a
//! test run inside go-algorand's `logic` package, never from this
//! implementation.

use algo_avm::disassembler::pc_details;
use serde_json::Value;

const FIXTURE: &str = include_str!("fixtures/pcdetails_go_parity.jsonl");

#[test]
fn pc_details_matches_go_for_every_pc_of_every_program() {
    let mut failures = Vec::new();
    let (mut programs, mut pcs) = (0, 0);
    for line in FIXTURE.lines().filter(|l| !l.is_empty()) {
        programs += 1;
        let case: Value = serde_json::from_str(line).expect("fixture row is JSON");
        let name = case["name"].as_str().expect("name");
        let program = hex::decode(case["program_hex"].as_str().expect("program_hex"))
            .expect("program_hex is hex");
        let details = case["details"].as_array().expect("details");
        assert_eq!(details.len(), program.len() + 2, "{name}: one text per pc");
        for (pc, want) in details.iter().enumerate() {
            pcs += 1;
            let want = want.as_str().expect("details are strings");
            let got = pc_details(&program, pc);
            if got != want && failures.len() < 40 {
                failures.push(format!(
                    "{name} pc={pc} (program {}):\n  go:   {want:?}\n  rust: {got:?}",
                    case["program_hex"].as_str().unwrap_or("?"),
                ));
            }
        }
    }
    assert!(
        programs > 100,
        "fixture unexpectedly small: {programs} programs"
    );
    assert!(
        failures.is_empty(),
        "pc_details differs from go-algorand's pcDetails (of {pcs} (program, pc) pairs, first {}):\n{}",
        failures.len(),
        failures.join("\n")
    );
}
