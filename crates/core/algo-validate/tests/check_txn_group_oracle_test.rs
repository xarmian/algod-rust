//! Issue #2544 (go v5.1 #6728): the group-validity decisions of go's
//! `transactions.CheckTxnGroup` / `CheckPaysetGroup` against rows generated by
//! the real go-algorand `v5.1.1-stable` functions
//! (`tools/checktxngroup-oracle`, fixture
//! `tests/fixtures/check_txn_group_oracle.jsonl`), crafted groups under both
//! values of `allowGroupedHeartbeats`: grouped heartbeats, duplicate
//! transactions, the three checks go removed (missing heartbeat body, unknown
//! type, box index), state proofs and the group-ID rules.
//!
//! The Rust equivalent of go's `checkTxnGroup` is `check_txn_group` (the state
//! proof and heartbeat rules) followed by the group-ID rules
//! (`GroupIdChecker`). The 16-member size limit is not part of go's function
//! (`Block.PaysetGroups` and the submission paths apply it), so it is not
//! applied here.

use algo_error::AlgoError;
use algo_types::SignedTransaction;
use algo_validate::{check_txn_group, GroupIdChecker};
use base64::Engine as _;

fn rust_verdict(group: &[SignedTransaction], allow_hb: bool) -> Result<(), String> {
    let text = |e: AlgoError| match e {
        AlgoError::Validation { message } => message,
        other => panic!("unexpected error kind: {other:?}"),
    };
    check_txn_group(group, allow_hb).map_err(text)?;
    let Some(first) = group.first() else {
        return Ok(());
    };
    let mut ids = GroupIdChecker::new(&first.txn, group.len()).rejecting_duplicates();
    for (i, stx) in group.iter().enumerate() {
        ids.check_member(i, &stx.txn)?;
    }
    ids.finish()
}

#[test]
fn check_txn_group_matches_go_on_every_oracle_row() {
    let fixture = include_str!("fixtures/check_txn_group_oracle.jsonl");
    let mut rows = 0usize;
    let mut mismatches = Vec::new();
    let mut by_name: std::collections::BTreeMap<(String, bool), (bool, String)> =
        Default::default();
    for line in fixture.lines().filter(|l| !l.trim().is_empty()) {
        let r: serde_json::Value = serde_json::from_str(line).expect("row");
        let name = r["name"].as_str().unwrap().to_string();
        let allow_hb = r["allow_hb"].as_bool().unwrap();
        let ok = r["ok"].as_bool().unwrap();
        let want_err = r["error"].as_str().unwrap_or("").to_string();

        // go's CheckPaysetGroup agrees with its CheckTxnGroup on every row.
        let entry = (ok, want_err.clone());
        if let Some(prev) = by_name.insert((name.clone(), allow_hb), entry.clone()) {
            assert_eq!(prev, entry, "{name}: go's two functions disagree");
        }
        if r["func"] != "txn" {
            continue;
        }

        let mut group = Vec::new();
        // an empty group is `null` (a nil go slice)
        for m in r["group"].as_array().map_or(&[][..], |a| a.as_slice()) {
            let bytes = base64::engine::general_purpose::STANDARD
                .decode(m.as_str().unwrap())
                .unwrap();
            group.extend(algo_codec::decode_signed_txn_stream(&bytes).expect("decode member"));
        }
        let got = rust_verdict(&group, allow_hb);
        let matches = match (&got, ok) {
            (Ok(()), true) => true,
            (Err(e), false) => *e == want_err,
            _ => false,
        };
        if !matches {
            mismatches.push(format!(
                "{name} (allowGroupedHeartbeats={allow_hb}): go ok={ok} err={want_err:?}, rust {got:?}"
            ));
        }
        rows += 1;
    }
    assert!(mismatches.is_empty(), "{}", mismatches.join("\n"));
    assert!(rows >= 90, "only {rows} oracle rows");
}
