//! Post-quantum (Falcon-1024) signature failure texts in simulate, pinned to
//! go-algorand v5.0.5-stable's `Simulator.Simulate` (issue #2438).
//!
//! The `"simulate"` cases of `algo-validate/tests/fixtures/pq_failure_texts.jsonl`
//! (generated by `tools/pq-failure-text-oracle/run-in-docker.sh`) carry the PQ
//! envelope go submitted (and the whole `SignedTxn`, issue #2451), its sender
//! and request flags, and go's outcome: no request error, the group
//! `FailureMessage` in full (go's `transaction %+v invalid : ` struct-dump
//! frame included) and `FailedAt`. Every PQ failure
//! is attributed to its transaction in go (`TxGroupError{GroupIndex: gi}` from
//! `stxnCoreChecks` / `logicSigVerify`, or `EvalFailureError` from
//! `validateFixedPlaceholderPQEnvelopes`), so none is a request error.

use algo_ledger::apply::pool_fixtures::funded_simulation_state;
use algo_ledger::simulation::{SimulationRequest, Simulator};
use algo_ledger::{LedgerState, LedgerStore};
use algo_types::consensus::CONSENSUS_V42;
use algo_types::{AccountData, Address};
use serde_bytes::ByteBuf;

const FIXTURE: &str = include_str!("../../algo-validate/tests/fixtures/pq_failure_texts.jsonl");

const FEE_SINK: Address = Address([0xFE; 32]);

fn setup_state(sender: Address) -> LedgerState {
    let mut state = funded_simulation_state();
    state.fee_sink = FEE_SINK;
    state.protocol = CONSENSUS_V42.to_string();
    state.set_account(
        &sender,
        AccountData {
            micro_algos: 10_000_000,
            ..Default::default()
        },
    );
    state.set_account(&FEE_SINK, AccountData::default());
    state
}

fn bytes(case: &serde_json::Value, key: &str) -> ByteBuf {
    ByteBuf::from(hex::decode(case[key].as_str().unwrap_or("")).unwrap())
}

#[test]
fn pq_failure_texts_match_go_in_simulate() {
    let cases: Vec<serde_json::Value> = FIXTURE
        .lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| serde_json::from_str::<serde_json::Value>(l).expect("fixture line is JSON"))
        .filter(|c| c["path"] == "simulate")
        .collect();
    assert_eq!(cases.len(), 12, "fixture must carry every simulate case");

    let mut mismatches = Vec::new();
    for case in &cases {
        let name = format!(
            "{} / {} (fix signers: {})",
            case["kind"].as_str().unwrap(),
            case["name"].as_str().unwrap(),
            case["fix_signers"]
        );
        let sender: Address = case["sender"].as_str().unwrap().parse().unwrap();
        // The transaction go submitted, its signature and envelope included:
        // the framed failure prints all of it.
        let mut group = algo_codec::decode_signed_txn_stream(
            &hex::decode(case["stxn"].as_str().unwrap()).unwrap(),
        )
        .expect("go's SignedTxn decodes");
        assert_eq!(group.len(), 1, "{name}");
        let stx = group.remove(0);
        assert_eq!(stx.txn.sender, sender, "{name}");
        let pq = if case["kind"] == "pqsig" {
            stx.pqsig.clone()
        } else {
            stx.lsig.as_ref().and_then(|l| l.pqsig.clone())
        }
        .expect("the case's PQ envelope");
        assert_eq!(pq.public_key, bytes(case, "pk"), "{name}");
        assert_eq!(pq.signature, bytes(case, "sig"), "{name}");

        let mut state = setup_state(sender);
        // go's simulation ledger: its genesis is the transaction's.
        state.genesis_hash = stx.txn.genesis_hash;
        state.genesis_id = stx.txn.genesis_id.clone();
        let request = SimulationRequest {
            txn_groups: vec![vec![stx]],
            allow_empty_signatures: true,
            fix_signers: case["fix_signers"].as_bool().unwrap(),
            ..Default::default()
        };
        let want_error = case["want_error"].as_str().unwrap();
        let want_message = case["want_failure_message"].as_str().unwrap();
        let want_failed_at: Vec<usize> = case["want_failed_at"]
            .as_array()
            .unwrap()
            .iter()
            .map(|v| v.as_u64().unwrap() as usize)
            .collect();

        let got = match Simulator::new(&mut state).simulate(request) {
            Err(e) => format!("request error {e}"),
            Ok(result) => {
                let group = &result.txn_groups[0];
                format!(
                    "failure {:?} at {:?}",
                    algo_validate::mask_heartbeat_pointer(
                        group.failure_message.as_deref().unwrap_or_default()
                    ),
                    group.failed_at.clone().unwrap_or_default()
                )
            }
        };
        assert!(want_error.is_empty(), "{name}: go reports no request error");
        let want = format!("failure {want_message:?} at {want_failed_at:?}");
        if got != want {
            mismatches.push(format!("{name}:\n    go:   {want}\n    rust: {got}"));
        }
    }
    assert!(
        mismatches.is_empty(),
        "simulate PQ failure texts differ from go v5.0.5:\n{}",
        mismatches.join("\n")
    );
}
