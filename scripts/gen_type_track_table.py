FIXTURE = ROOT / "crates/core/algo-avm/tests/fixtures/go_op_types.jsonl"
OUT = ROOT / "crates/core/algo-avm/src/type_track_table.rs"
MAX_UINT64 = (1 << 64) - 1
MAX_STRING = 4096

